-- Historical payout snapshots are required for honest payout-aware research replay.
-- Apply this migration only to the dedicated switrade Database 2 project.

create table if not exists public.even_odd_payout_quote_snapshots (
    id bigint generated by default as identity primary key,
    market_symbol text not null check (market_symbol ~ '^[A-Za-z0-9_]{2,32}$'),
    currency text not null check (currency ~ '^[A-Z]{3}$'),
    stake numeric(20, 8) not null check (stake > 0),
    quoted_at timestamptz not null,
    spot_time bigint not null check (spot_time > 0),
    even_ask_price numeric(20, 8) not null check (even_ask_price > 0),
    even_payout numeric(20, 8) not null check (even_payout > even_ask_price),
    odd_ask_price numeric(20, 8) not null check (odd_ask_price > 0),
    odd_payout numeric(20, 8) not null check (odd_payout > odd_ask_price),
    source text not null default 'deriv_public_websocket',
    metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
    created_at timestamptz not null default now(),
    constraint even_odd_payout_quote_snapshot_unique
        unique (market_symbol, currency, stake, spot_time)
);

create index if not exists even_odd_payout_quote_lookup_idx
    on public.even_odd_payout_quote_snapshots
       (market_symbol, currency, stake, spot_time desc);

alter table public.even_odd_payout_quote_snapshots enable row level security;
revoke all on table public.even_odd_payout_quote_snapshots from anon, authenticated;
grant select, insert on table public.even_odd_payout_quote_snapshots to service_role;
